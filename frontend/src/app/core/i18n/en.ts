// يحوّل كل قيمة نصية إلى النوع string بشكل متكرر، حتى يحتوي ar.ts نصوص مختلفة بنفس المفاتيح.
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };
