import {
  REFERENCE,
  SAUDI_MOBILE,
  addDays,
  localPhone,
  normalizeReference,
  riyadhMinutesNow,
  riyadhToday,
  startTimes,
  statusTone,
} from './masar';

describe('masar helpers', () => {
  it('accepts the Saudi mobile formats the server accepts, and nothing else', () => {
    for (const ok of [
      '0551234567',
      '551234567',
      '+966551234567',
      '00966551234567',
      '055 123 4567',
      '055-123-4567',
    ]) {
      expect(SAUDI_MOBILE.test(ok), ok).toBe(true);
    }
    // Landline (01…), too short, too long, not starting with 5. / رقم ثابت، قصير، طويل، ما يبدأ بـ 5.
    for (const bad of ['0112345678', '05512345', '05512345678', '0451234567', 'abc']) {
      expect(SAUDI_MOBILE.test(bad), bad).toBe(false);
    }
  });

  it('shows stored numbers the local way', () => {
    expect(localPhone('966551234567')).toBe('0551234567');
    expect(localPhone(null)).toBe('');
  });

  it('normalises a typed reference and rejects look-alike characters', () => {
    expect(normalizeReference(' ms7k3qx9pa ')).toBe('MS-7K3QX9PA');
    expect(normalizeReference('MS-7K3QX9PA')).toBe('MS-7K3QX9PA');
    expect(REFERENCE.test('ms-7k3qx9pa')).toBe(true);
    // 0, O, 1, I and L are never generated by the server. / الخادم ما يولّد 0 و O و 1 و I و L أبدًا.
    expect(REFERENCE.test('MS-7K3QX9P0')).toBe(false);
    expect(REFERENCE.test('MS-7K3QXIPA')).toBe(false);
  });

  it('uses the Riyadh calendar day, not the browser one', () => {
    // 22:30 UTC on 31 Dec is already 1 Jan in Riyadh (UTC+3).
    // الساعة 22:30 UTC يوم 31 ديسمبر هي أصلًا 1 يناير في الرياض (UTC+3).
    const instant = new Date('2026-12-31T22:30:00Z');
    expect(riyadhToday(instant)).toBe('2027-01-01');
    expect(riyadhMinutesNow(instant)).toBe(90);
  });

  it('adds days across month and year ends', () => {
    expect(addDays('2026-12-31', 1)).toBe('2027-01-01');
    expect(addDays('2028-02-28', 1)).toBe('2028-02-29');
    expect(addDays('2026-03-01', -1)).toBe('2026-02-28');
  });

  it('offers only half-hour starts that finish by 20:00', () => {
    const oneHour = startTimes(60);
    expect(oneHour[0]).toBe('08:00');
    expect(oneHour.at(-1)).toBe('19:00');
    expect(oneHour).toContain('12:30');
    // An 8-hour job can start at 12:00 at the latest. / شغل 8 ساعات آخر بداية له 12:00.
    expect(startTimes(480).at(-1)).toBe('12:00');
  });

  it('groups statuses into badge colours', () => {
    expect(statusTone('NEW')).toBe('warn');
    expect(statusTone('SCHEDULED')).toBe('info');
    expect(statusTone('COMPLETED')).toBe('success');
    expect(statusTone('REJECTED')).toBe('danger');
    expect(statusTone('CANCELLED')).toBe('muted');
  });
});
